# -*- coding: utf-8 -*-
"""
verify.py — числовая верификация snow_melt_new.xlsx.
1) Пересчёт всей модели в Python ( зеркало формул листа «Расчёт» ).
2) Контроль ключевых значений (сходимость проходов, РТ насоса, диапазон скорости).
3) Проверка структуры: главные формулы и ссылки в ячейках.
"""
import math
import openpyxl

# ---------- модель (зеркало формул) ----------
X = dict(
    tв=-10.0, tн=5.0, tст=2.0, hсн=2.0, tпод=55.0, vн=3.0, Fст=14.0, τмин=120.0,
    b=0.2, dн=0.020, s=0.002, λтр=0.41,
    d_стяж=0.060, λ_стяж=1.75, d_плит=0.020, λ_плит=3.5,
    d_эппс=0.050, λ_эппс=0.034, d_бет=0.300, λ_бет=1.75, R_пес=2.1,
    ρж=1032.0, cж=3.64, kА=1.39,
    ρл=900.0, cл=2.1, λл=330.0, cв=4.2, ε=0.055, Co=5.77, αв=11.5,
    # местные сопротивления, магистраль и запас 1,2 исключены из файла И из зеркала (решение 06.11.2026)
    v_пр=0.45,
)
HQ = {
    "Grundfos UPS 25-20":        [2.0, 1.8, 1.35, 0.85, 0.3, 0.0, 0.0],
    "Grundfos UPS 25-40":        [4.0, 3.6, 2.9, 2.0, 1.0, 0.2, 0.0],
    "Grundfos UPS 25-50":        [5.0, 4.6, 3.8, 2.7, 1.5, 0.5, 0.0],
    "Grundfos UPS 25-60":        [6.0, 5.5, 4.8, 3.9, 2.8, 1.5, 0.5],
    "Wilo Yonos Picos2 25/1-4":  [4.0, 3.75, 3.3, 2.7, 1.9, 1.0, 0.3],
    "Wilo Yonos Picos2 25/1-6":  [6.0, 5.6, 5.0, 4.2, 3.2, 2.0, 0.8],
}
QKNOTS = [0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0]

def run(pump="Grundfos UPS 25-20", tпод=None, vн=None, τмин=None, verbose=True):
    X["tпод"] = X["tпод"] if tпод is None else tпод
    X["vн"] = X["vн"] if vн is None else vн
    X["τмин"] = X["τмин"] if τмин is None else τмин
    X["αн"] = 8.7 + 2.6 * X["vн"]
    dв = X["dн"] - 2 * X["s"]
    ω = math.pi * dв ** 2 / 4
    Rвверх = X["d_стяж"] / X["λ_стяж"] + X["d_плит"] / X["λ_плит"]
    Rвниз = X["d_эппс"] / X["λ_эппс"] + X["d_бет"] / X["λ_бет"] + X["R_пес"]

    Q1 = X["hсн"] / 1000 * X["ρл"] * X["cл"] * (0 - X["tв"])
    Q2 = X["hсн"] / 1000 * X["ρл"] * X["λл"]
    Q3 = X["hсн"] / 1000 * X["ρл"] * X["cв"] * (X["tст"])
    τ = X["τмин"] * 60
    # потери масштабируются на ВЕСЬ период таяния (поверхность отдаёт тепло всё τ)
    Qизл = X["ε"] * X["Co"] * ((0 + 273) / 100) ** 4 * τ / 1000
    # вариант 2: конвекция привязана к ветру — тот же αн, что и в Rв; коэф. 0,5 исходника отброшен
    Qкон = X["αн"] * (0 - X["tв"]) * τ / 1000
    ΣQ = Q1 + Q2 + Q3 + Qизл + Qкон

    Rв = 1 / X["αв"] + Rвверх + 1 / X["αн"] + X["s"] / X["λтр"]

    def pass_(tср):
        η = ((tср - X["tв"]) * Rвниз) / ((tср - X["tв"]) * Rвниз + (tср - X["tн"]) * Rвверх)
        n1 = ΣQ / (η * τ)
        tмин = 1000 * n1 * Rв + X["tст"]
        return η, n1, tмин, (X["tпод"] + tмин) / 2
    tср = (X["tпод"] + X["tст"]) / 2
    hist = []
    for k in range(3):
        η, n1, tмин, tср_next = pass_(tср)
        hist.append((tср, η, n1, tмин, tср_next))
        tср = tср_next
    tср, η, n1, tмин, _ = hist[2]
    N1 = n1 * X["Fст"]
    tдоп = X["tпод"] - tмин

    result = dict(dв=dв, ω=ω, Rвверх=Rвверх, Rвниз=Rвниз, Rв=Rв, ΣQ=ΣQ, n1=n1,
                  tмин=tмин, tдоп=tдоп, N1=N1)

    # ---- guard: неосуществимый режим ----
    # если допустимый перепад исчез (tмин дошло до подачи или выше) —
    # скомпоновать петли нельзя: f_макс <= 0 -> i <= 0 (и v_пет <= 0 крашит v**1.79).
    if tдоп <= 0.02:
        if verbose:
            print("N1={:.3f} kW; tдоп={:.2f} K".format(N1, tдоп))
            print("РЕЖИМ НЕОСУЩЕСТВИМ: tмин = {:.1f} °C ≥ tпод = {:.0f} °C (допустимая площадь петли ≤ 0).".format(
                tмин, X["tпод"]))
            print("Увеличьте время таяния τ и/или температуру подачи tпод.")
            print()
        result.update(осущ=False, f_макс=None, L_макс=None, i=None, f_факт=None,
                      L_ср=None, Gрт=None, Hрт=None, v_факт=None)
        return result
    result["осущ"] = True

    Δt_м = n1 * X["b"] / (X["v_пр"] * ω * X["ρж"] * X["cж"])
    t1 = Δt_м / X["b"]
    f_макс = tдоп / t1
    L_макс = f_макс / X["b"]
    i = math.ceil(X["Fст"] / f_макс - 1e-12)
    f_ф = X["Fст"] / i
    L_ср = f_ф / X["b"]
    G_пет = 3600 * X["v_пр"] * ω
    G_общ = i * G_пет
    Δt_ф_пр = n1 * f_ф / (X["v_пр"] * ω * X["ρж"] * X["cж"])
    tобр_п = X["tпод"] - Δt_ф_пр

    # ---- рабочая точка ----
    def H_нас(q):
        h = HQ[pump]
        if q <= QKNOTS[1]:
            return h[0] + (h[1] - h[0]) * (q - QKNOTS[0]) / (QKNOTS[1] - QKNOTS[0])
        for j in range(1, 6):
            if q <= QKNOTS[j + 1]:
                return h[j] + (h[j + 1] - h[j]) * (q - QKNOTS[j]) / (QKNOTS[j + 1] - QKNOTS[j])
        return 0.0

    def H_сети(q):
        v_пет = q / (i * 3600 * ω)
        # упрощённая схема: только потери по длине петли
        d_дл = X["kА"] * 32000 * v_пет ** 1.79 / (dв * 1000) ** 1.29 * L_ср
        return [v_пет, d_дл, d_дл / (X["ρж"] * 9.81)]

    rows = []
    for k in range(25):
        q = 0.125 * k
        v_пет, d_дл, h_сети = H_сети(q)
        h_нас = H_нас(q)
        rows.append((q, v_пет, h_сети, h_нас, h_нас - h_сети))
    n_neg = sum(1 for r in rows if r[4] < 0)
    if n_neg == 0:
        Gрт = Hрт = v_факт = None
    else:
        k_first_neg = 25 - n_neg          # 1-й отрицательный в 0-индексе
        a, b_ = rows[k_first_neg - 1], rows[k_first_neg]
        Δa, Δb = a[4], b_[4]
        Gрт = a[0] + Δa * (b_[0] - a[0]) / (Δa - Δb)
        Hрт = a[3] + (b_[3] - a[3]) * (Gрт - a[0]) / (b_[0] - a[0])
        v_факт = Gрт / (i * 3600 * ω)
        Δt_факт = n1 * f_ф / (v_факт * ω * X["ρж"] * X["cж"])
        tобр = X["tпод"] - Δt_факт
        tср_ф = (X["tпод"] + tобр) / 2
        η_ф, n1_ф, _, _ = pass_(tср_ф)
        N1_ф = n1_ф * X["Fст"]

    if verbose:
        print("=== РАСЧЁТ tпод = {} °C, насос: {}".format(X["tпод"], pump))
        print("dв={:.4f} м  ω={:.3e} м²  Rвверх={:.4f}  Rвниз={:.4f}  Rв={:.4f}".format(dв, ω, Rвверх, Rвниз, Rв))
        print("Q1={:.2f} Q2={:.2f} Q3={:.2f} Qизл={:.2f} αн={:.2f} Qкон={:.2f} ΣQ={:.2f} кДж/м²".format(
            Q1, Q2, Q3, Qизл, X["αн"], Qкон, ΣQ))
        for k, (t, e, n, tm, tn) in enumerate(hist, 1):
            print("проход {}: tср={:.2f} η={:.5f} n1={:.5f} tмин={:.2f} -> tсрн={:.2f}".format(k, t, e, n, tm, tn))
        print("N1={:.3f} kW; tдоп={:.2f} K; Δt(1м)={:.3f} К/м; t1={:.3f} К/м²".format(N1, tдоп, Δt_м, t1))
        print("f_макс={:.2f} м²; L_макс={:.1f} м; i={} ; f_факт={:.2f} м²; L_СР={:.1f} м".format(
            f_макс, L_макс, i, f_ф, L_ср))
        print("расход: на петлю {:.3f}, общий {:.3f} м³/ч; Δt_факт(пр)={:.2f} К; tобр(пр)={:.2f} °C".format(
            G_пет, G_общ, Δt_ф_пр, tобр_п))
        print("РТ: nΔ<0={};".format(n_neg), end=" ")
        if Gрт is not None:
            print("Gрт={:.3f} м³/ч; Hрт={:.2f} м; v_петл={:.3f} м/с; Δt={:.2f} К; tобр={:.2f}; N1_факт={:.3f} кВт".format(
                Gрт, Hрт, v_факт, Δt_факт, tобр, N1_ф))
            if 0.2 <= v_факт <= 0.5:
                print("статус скорости: OK")
            else:
                print("статус скорости: ВНИМАНИЕ — вне диапазона!")
    else:
        print("пересечение не найдено!")
    result.update(f_макс=f_макс, L_макс=L_макс, i=i, f_факт=f_ф, L_ср=L_ср,
                  Gрт=Gрт, Hрт=(Hрт if Gрт is not None else None),
                  v_факт=(v_факт if Gрт is not None else None))
    return result

# ---------- проверки (физические критерии, БЕЗ опоры на значения исходника) ----------
print("########## ЭТАЛОН (τ=120 мин, vн=3) — напряжённый режим ##########")
r1 = run()
print()
print("########## τ=300 мин — комфортный режим ##########")
r300 = run(τмин=300.0)
print()
print("########## τ=300, vн=5 (усиленный ветер) ##########")
r_w5 = run(τмин=300.0, vн=5.0)
print()
print("########## τ=300, vн=10 (сильный ветер — за пределом осуществимости) ##########")
r_w10 = run(τмин=300.0, vн=10.0)
print()
print("########## τ=300, tпод = 45 °C (стресс по подаче) ##########")
r45 = run(τмин=300.0, tпод=45.0, vн=3.0)

# физика: сопротивления слоёв (сложение по заданным слоям)
assert abs(r1["Rвверх"] - 0.04) < 1e-6, "Rвверх = стяжка + плитка должен быть ≈ 0,040"
assert abs(r1["Rвниз"] - 3.7424) < 1e-3, "Rвниз = ЭППС + бетон + песок должен быть ≈ 3,742"
# физика: мощность положительна и разумна для Fст = 14 м²
assert 1.0 <= r1["N1"] <= 10.0, "N1 в разумном диапазоне, кВт: {}".format(r1["N1"])
# напряжённый дефолт (τ=120): tмин почти у подачи, но режим осуществим;
# скорость при РТ ниже нормы — это осознанное решение (файл показывает напряжённый режим)
assert r1["осущ"] and r1["tдоп"] > 0, "дефолтный режим должен быть осуществим"
assert 53.0 < r1["tмин"] < 55.0, "tмин дефолта ≈ 54,8 (получено: {})".format(r1["tмин"])
assert r1["Gрт"] is not None and 0 < r1["Gрт"] < 3.0, "РТ внутри таблицы"
assert r1["v_факт"] is not None and r1["v_факт"] < 0.2, \
    "при τ=120 скорость при РТ ниже нормы (ВНИМАНИЕ в файле): {}".format(r1["v_факт"])
assert r1["L_ср"] < 5.0, "при τ=120 петли короткие: Lср = {}".format(r1["L_ср"])
# комфортный τ=300: скорость в норме, одна петля 70 м
assert r300["осущ"] and 0.2 <= r300["v_факт"] <= 0.5, \
    "при τ=300 скорость при РТ в норме 0,2–0,5 м/с (получено: {})".format(r300["v_факт"])
assert r300["i"] == 1 and abs(r300["L_ср"] - 70.0) < 0.5, \
    "при τ=300 одна петля: i=1, Lср = Fст/b = 70 м (получено i={}, Lср={})".format(r300["i"], r300["L_ср"])
assert 1.0 <= r300["N1"] <= 10.0, "N1(τ=300) в разумном диапазоне, кВт: {}".format(r300["N1"])
# монотонность по ветру: L_макс ↓, tмин ↑
assert r_w5["L_макс"] < r300["L_макс"], "усиление ветра сокращает допустимую длину петли"
assert r_w5["tмин"] > r300["tмин"], "усиление ветра повышает минимальную температуру"
assert r_w5["осущ"], "при vн=5 и τ=300 режим ещё осуществим"
# сильный ветер при τ=300: tмин уходит выше подачи -> guard объявляет неосуществимость
assert r_w10["осущ"] is False and r_w10["tмин"] > 55.0, \
    "при vн=10 и τ=300 режим неосуществим (tмин = {})".format(r_w10["tмин"])
# стресс по подаче: tмин подступает к 45 сверху, но ниже tпод
assert r45["осущ"] and 44.0 < r45["tмин"] < 45.0, \
    "при tпод=45 и τ=300: 44,2 < tмин < 45 (получено {})".format(r45["tмин"])

