    ("H35 Rвниз", str(ws["H35"].value).startswith("=H29/H30")),
    ("H61 ΣQ", str(ws["H61"].value).startswith("=H55+H56")),
    ("H58 Qизл ×τ", str(ws["H58"].value).startswith("=H46*H47*POWER((0+273)/100,4)*H14*60/1000")),
    ("H60 Qкон ×τ", str(ws["H60"].value).startswith("=H59*(0-H7)*H14*60/1000")),
    ("H64 Rв", str(ws["H64"].value).startswith("=1/H48")),
    ("проход 2 tср (=H72)", ws["H73"].value == "=H72"),
    ("H97 формула Lср", ws["H97"].value == "=H96/H19"),
    ("H143 Qрт (INDEX+COUNTIF)", "INDEX($B$116:$B$140" in str(ws["H143"].value)),
    ("H143 использует Δ-колонку G", "$G$116:$G$140" in str(ws["H143"].value)),
    ("H144 напор насоса — колонка F", "$F$116:$F$140" in str(ws["H144"].value)),
    ("заголовок таблицы упрощён", "H насоса" in str(ws.cell(row=115, column=6).value)),
    ("сетка Q в B140", ws.cell(row=140, column=2).value == 3.0 or abs(ws.cell(row=140, column=2).value - 3.0) < 1e-9),
    ("Hнас в F116 (IF-интерп.)", str(ws.cell(row=116, column=6).value).startswith("=IF(")),
    ("итог Lср H156", ws["H156"].value == "=H97"),
